def get_rule(rule_id: str) -> RuleType:
    return RULES.get(rule_id) or RULES["X00"]


def format_citation(refs: tuple[Ref, ...] | list[Ref]) -> str:
    """«Правила … (утв. постановлением …), п. 20; п. 31» — по каждому документу отдельно."""
    by_source: dict[str, list[str]] = {}
    for ref in refs:
        by_source.setdefault(ref.source, []).append(ref.point)
    parts = []
    for code, points in by_source.items():
        src = SOURCES[code]
        parts.append(f"{src.cite}, {'; '.join(points)}")
    return "; ".join(parts)


def citation_for(rule: RuleType) -> str:
    return format_citation(rule.verified_refs)


def build_description(rule: RuleType, observed: str) -> str:
    """Текст поля description в ответе API: что видно → почему → источник."""
    observed = observed.strip().rstrip(".")
    text = f"{observed}. Почему это может быть нарушением: {rule.why}"
    citation = citation_for(rule)
    if citation:
        text += f" Источник: {citation}."
    return text


def ref_to_dict(ref: Ref) -> dict:
    src = SOURCES[ref.source]
    return {
        "source": src.code,
        "source_title": src.title,
        "act": src.act,
        "url": src.url,
        "point": ref.point,
        "quote": ref.quote,
        "verified": ref.verified,
    }


def rule_to_dict(rule: RuleType) -> dict:
    return {
        "id": rule.id,
        "title": rule.title,
        "group": rule.group,
        "level": rule.level,
        "hint": rule.hint,
        "why": rule.why,
        "citation": citation_for(rule),
        "reportable": rule.is_reportable,
        "refs": [ref_to_dict(r) for r in rule.refs],
    }


