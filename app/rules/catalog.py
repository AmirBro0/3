"""Каталог типов нарушений и нормативных источников.

Единственный источник правды для текста «почему это может быть нарушением» и ссылок
на пункты. Модели НЕ генерируют ссылки сами: детектор называет только rule_id, а
документ и пункт берутся отсюда. Так в ответе не бывает выдуманных пунктов (критерий 4).

verified=True — пункт найден в действующей редакции на zakon.uchet.kz (зеркало adilet)
17.10.2026; quote — дословный фрагмент оттуда. Перед сдачей сверьте всё на
adilet.zan.kz. Пункты с verified=False в описание для жюри не попадают: если у типа
нет ни одного сверенного пункта, нарушение уходит в «на проверку» (только интерфейс).
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Source:
    code: str
    title: str
    act: str
    url: str
    kind: str = "rules"  # "rules" (Правила НБРК) | "law" (закон)

    @property
    def cite(self) -> str:
        if self.kind == "law":
            return f"{self.title} {self.act}"
        return f"{self.title} ({self.act})"


@dataclass(frozen=True)
class Ref:
    source: str
    point: str
    quote: str | None = None
    verified: bool = False


@dataclass(frozen=True)
class RuleType:
    id: str
    title: str
    group: str
    level: str  # A — видно однозначно; B — при чётком кадре; C — только явные случаи
    hint: str   # что должно быть видно на видео (подсказка и для людей, и для VLM)
    why: str    # норма простыми словами, одна-две фразы, с точкой в конце
    refs: tuple[Ref, ...] = field(default_factory=tuple)

    @property
    def verified_refs(self) -> tuple[Ref, ...]:
        return tuple(r for r in self.refs if r.verified)

    @property
    def is_reportable(self) -> bool:
        return bool(self.verified_refs)


